using System.Text;
using System.Text.RegularExpressions;

namespace hrms_api.Services;

public class AiScreeningPromptBuilder : IAiScreeningPromptBuilder
{
    private const int MaxJDLength = 4000;
    private const int MaxResumeLength = 8000;
    private const int MaxPromptLength = 15000;

    public string BuildPrompt(string jdText, string resumeText) =>
        BuildPromptText(jdText, resumeText);

    public AiScreeningPromptBuildResult BuildCompressedPrompt(string jdText, string resumeText)
    {
        var compressedJd = ScreeningTextCompressor.CompressJobDescription(jdText, MaxJDLength);
        var compressedResume = ScreeningTextCompressor.CompressResume(resumeText, MaxResumeLength);
        var prompt = BuildPromptText(compressedJd, compressedResume);

        if (prompt.Length > MaxPromptLength)
        {
            var overBy = prompt.Length - MaxPromptLength;
            var resumeBudget = Math.Max(5000, compressedResume.Length - overBy - 1000);
            compressedResume = ScreeningTextCompressor.CompressResume(resumeText, resumeBudget);
            prompt = BuildPromptText(compressedJd, compressedResume);
        }

        if (prompt.Length > MaxPromptLength)
        {
            var overBy = prompt.Length - MaxPromptLength;
            var jdBudget = Math.Max(2500, compressedJd.Length - overBy - 1000);
            compressedJd = ScreeningTextCompressor.CompressJobDescription(jdText, jdBudget);
            prompt = BuildPromptText(compressedJd, compressedResume);
        }

        return new AiScreeningPromptBuildResult(prompt, compressedJd, compressedResume);
    }

    private static string BuildPromptText(string jdText, string resumeText) => $$"""
